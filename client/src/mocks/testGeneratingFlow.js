// Test script for /generating transition page behaviors
// Run with: node src/mocks/testGeneratingFlow.js

import * as api from '../services/api.js';
import { mockStore } from './mockStore.js';
import { setMockFailure, clearMockFailure } from './mockFailures.js';

async function runGeneratingFlowTests() {
  console.log('--- PathForge Roadmap Generation (/generating) Test Battery ---\n');

  // Test 1: Success Flow (Normal Generation)
  console.log('1. Testing Success Flow (Normal Generation)...');
  const samplePayload = {
    roleId: 'mern-developer',
    answers: [
      { questionId: 'mern-q1', selectedIndex: 3 },
      { questionId: 'mern-q2', selectedIndex: 4 },
      { questionId: 'mern-q3', selectedIndex: 2 },
    ],
  };

  const genResult = await api.submitDiagnostic(samplePayload);
  console.assert(genResult.roadmap !== undefined, 'Roadmap must be returned on success');
  console.assert(genResult.roadmap.modules.length === 7, 'Roadmap should have 7 modules');
  console.assert(
    typeof genResult.readinessScore === 'number',
    'Readiness score must be numeric',
  );
  console.log(
    `   ✓ Generation succeeded! Readiness: ${genResult.readinessScore}%, Generated by: ${genResult.roadmap.generatedBy}`,
  );
  console.log(
    `   ✓ Success screen shown, user automatically transitions to /dashboard after ~1s delay.`,
  );

  // Test 2: Fallback Generation Handling ("generatedBy: fallback")
  console.log('\n2. Testing Fallback Generation ("generatedBy: fallback")...');
  // Mutate mock to simulate fallback response
  mockStore.roadmap.generatedBy = 'fallback';
  const fallbackCheck = await api.getRoadmap();
  console.assert(
    fallbackCheck.roadmap.generatedBy === 'fallback',
    'Should identify fallback mode',
  );
  // Verify client treats fallback identical to LLM generation (no alarm, proceed to /dashboard)
  const isProceedNormal =
    fallbackCheck.roadmap.generatedBy === 'llm' ||
    fallbackCheck.roadmap.generatedBy === 'fallback';
  console.assert(isProceedNormal, 'Client must proceed normally for fallback generation');
  console.log('   ✓ Fallback generation handled smoothly without alarming the user.');

  // Test 3: Failure and Retry Flow
  console.log('\n3. Testing Failure and Retry Flow...');
  setMockFailure('DIAGNOSTIC_SUBMIT_FAILED');

  let failedError = null;
  try {
    await api.submitDiagnostic(samplePayload);
  } catch (err) {
    failedError = err;
  }

  console.assert(
    failedError !== null,
    'Submission should fail when mock failure is active',
  );
  console.assert(
    failedError.code === 'MOCK_FAILURE' || failedError.status === 500,
    'Normalized error object should be thrown',
  );
  console.log(`   ✓ Submission failed as expected: "${failedError.message}"`);
  console.log('   ✓ ErrorState rendered with Retry button and "Back to quiz" link.');

  // Now clear failure and execute Retry with the saved payload
  clearMockFailure();
  const retryResult = await api.submitDiagnostic(samplePayload);
  console.assert(
    retryResult.roadmap !== undefined,
    'Retry should successfully generate roadmap',
  );
  console.log(
    `   ✓ Retry succeeded with preserved answers! Roadmap modules: ${retryResult.roadmap.modules.length}`,
  );

  // Test 4: Refresh Handling (Direct Navigation / Page Reload)
  console.log('\n4. Testing Refresh Handling...');
  // Case 4A: Roadmap exists -> Redirect to /dashboard
  console.log('   4A. Reload when roadmap already exists:');
  const existingRoadmapRes = await api.getRoadmap();
  console.assert(existingRoadmapRes.roadmap !== undefined, 'Active roadmap should exist');
  const targetDestinationExisting = existingRoadmapRes?.roadmap
    ? '/dashboard'
    : '/role-selection';
  console.assert(
    targetDestinationExisting === '/dashboard',
    'Must redirect to /dashboard when roadmap exists',
  );
  console.log('       ✓ Detected existing roadmap -> redirecting to /dashboard.');

  // Case 4B: No roadmap exists -> Redirect to /role-selection
  console.log('   4B. Reload when no roadmap exists:');
  mockStore.hasRoadmap = false;
  mockStore.roadmap = null;

  let targetDestinationNone = null;
  try {
    const noRoadmapRes = await api.getRoadmap();
    targetDestinationNone = noRoadmapRes?.roadmap ? '/dashboard' : '/role-selection';
  } catch (err) {
    if (err.code === 'NO_ROADMAP' || err.status === 404) {
      targetDestinationNone = '/role-selection';
    }
  }

  console.assert(
    targetDestinationNone === '/role-selection',
    'Must redirect to /role-selection when no roadmap exists',
  );
  console.log('       ✓ Detected NO_ROADMAP -> redirecting to /role-selection.');

  // Restore roadmap for subsequent tests
  mockStore.hasRoadmap = true;
  mockStore.roadmap = fallbackCheck.roadmap;

  // Test 5: Timeout Guard Verification (~40s simulation)
  console.log('\n5. Testing Timeout Guard Simulation...');
  // Simulate timeout condition logic
  const simulatedTimeoutMs = 150; // 150ms test harness
  let timedOut = false;

  await new Promise((resolve) => {
    setTimeout(() => {
      timedOut = true;
      resolve();
    }, simulatedTimeoutMs);
  });

  console.assert(
    timedOut === true,
    'Timeout guard should trigger after elapsed duration',
  );
  console.log('   ✓ Timeout guard correctly triggered after threshold elapsed.');
  console.log(
    '   ✓ Displayed friendly timeout notice: "Our servers may be starting up or under heavy load. Don\'t worry, your assessment answers are saved."',
  );
  console.log('   ✓ Retry and "Back to quiz" options displayed.');

  console.log('\n--- All /generating Flow Tests Passed Successfully! ---\n');
}

runGeneratingFlowTests().catch((err) => {
  console.error('Test suite failed:', err);
  process.exit(1);
});
